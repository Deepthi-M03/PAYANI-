"""Catalogue storage and the in-memory timetable used for routing."""

from __future__ import annotations

import threading
from datetime import date

from sqlalchemy import delete, func, select
from sqlalchemy.orm import Session

from payani.core.db import utcnow, uuid7
from payani.domain import catalog_synth as synth
from payani.domain.catalog_synth import Stop, Train
from payani.modules.book.models import ProviderSyncRun, Station, TrainRow, TrainStop

LICENCE = ("Synthetic timetable generated by PAYANI (no third-party data). Station codes and "
           "names are public facts; coordinates are approximate and hand-entered.")

_cache: dict = {"trains": None}
_lock = threading.Lock()


def load_synthetic(db: Session) -> int:
    """Idempotent: replaces the synthetic catalogue and records a provider sync run."""
    run = ProviderSyncRun(id=uuid7(), provider="payani-synthetic", dataset="timetable-v1",
                          status="running", rows=0, as_of=date.fromisoformat(synth.SNAPSHOT),
                          licence=LICENCE, source_url=None)
    db.add(run)
    db.execute(delete(TrainRow).where(TrainRow.source == synth.SOURCE))
    existing = set(db.scalars(select(Station.code)))
    for s in synth.STATIONS:
        if s.code not in existing:
            db.add(Station(id=uuid7(), code=s.code, name=s.name, state=s.state, lat=s.lat, lon=s.lon,
                           source=synth.SOURCE))
    db.flush()
    rows = 0
    for t in synth.generate_trains():
        tr = TrainRow(id=uuid7(), number=t.number, name=t.name, kind=t.kind, running_days=t.running_days,
                      classes=",".join(t.classes), source=synth.SOURCE, snapshot=run.as_of)
        db.add(tr)
        db.flush()
        for i, st in enumerate(t.stops):
            db.add(TrainStop(id=uuid7(), train_id=tr.id, seq=i, station_code=st.station, arr_min=st.arr,
                             dep_min=st.dep, distance_km=st.distance_km))
            rows += 1
    run.rows, run.status, run.finished_at = rows, "succeeded", utcnow()
    db.commit()
    invalidate()
    return rows


def invalidate() -> None:
    with _lock:
        _cache["trains"] = None


def timetable(db: Session) -> list[Train]:
    with _lock:
        if _cache["trains"] is not None:
            return _cache["trains"]
    trains = [
        Train(r.number, r.name, r.kind, r.running_days, tuple(r.classes.split(",")),
              [Stop(s.station_code, s.arr_min, s.dep_min, s.distance_km) for s in r.stops])
        for r in db.scalars(select(TrainRow)).all()
    ]
    with _lock:
        _cache["trains"] = trains
    return trains


def freshness(db: Session) -> dict:
    run = db.scalar(select(ProviderSyncRun).where(ProviderSyncRun.status == "succeeded")
                    .order_by(ProviderSyncRun.started_at.desc()))
    trains = db.scalar(select(func.count()).select_from(TrainRow))
    if run is None:
        return {"status": "empty", "trains": 0}
    age = (date.today() - run.as_of).days
    return {"status": "stale" if age > 180 else "ok", "provider": run.provider, "dataset": run.dataset,
            "as_of": run.as_of.isoformat(), "age_days": age, "rows": run.rows, "trains": trains,
            "licence": run.licence, "confidence": "simulated"}

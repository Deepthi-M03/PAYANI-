"""Catalogue storage and the in-memory timetable used for routing.

Two catalogues can live in the database side by side:
* the synthetic catalogue (`source = payani-synthetic-v1`, `dataset_id IS NULL`), labelled Simulated;
* at most one active imported dataset (`dataset_id` = the active `timetable_imports` row),
  labelled Scheduled and always shown with its source, publication date and age.

Journey search uses the imported dataset when one is active and the synthetic catalogue
otherwise. Each process caches the timetable and checks the active import id on every
call (one indexed lookup), so all workers switch together after an import.
"""

from __future__ import annotations

import threading
from collections import defaultdict
from datetime import date

from sqlalchemy import delete, func, select
from sqlalchemy.orm import Session

from payani.core.db import utcnow, uuid7
from payani.domain import catalog_synth as synth
from payani.domain.catalog_synth import Stop, Train
from payani.domain.timetable_import import freshness_label
from payani.modules.book.models import ProviderSyncRun, Station, TrainRow, TrainStop
from payani.modules.timetable.models import TimetableImport

LICENCE = ("Synthetic timetable generated by PAYANI (no third-party data). Station codes and "
           "names are public facts; coordinates are approximate and hand-entered.")
LARGE_TIMETABLE = 400  # above this many trains, searches allow one change (see routing.candidate_trains)

_cache: dict = {"key": None}
_lock = threading.Lock()


def load_synthetic(db: Session) -> int:
    """Idempotent: replaces the synthetic catalogue and records a provider sync run.
    Imported trains are untouched."""
    run = ProviderSyncRun(id=uuid7(), provider="payani-synthetic", dataset="timetable-v1",
                          status="running", rows=0, as_of=date.fromisoformat(synth.SNAPSHOT),
                          licence=LICENCE, source_url=None)
    db.add(run)
    db.execute(delete(TrainRow).where(TrainRow.source == synth.SOURCE))
    existing = {s.code: s for s in db.scalars(select(Station))}
    for s in synth.STATIONS:
        row = existing.get(s.code)
        if row is None:
            db.add(Station(id=uuid7(), code=s.code, name=s.name, state=s.state, lat=s.lat, lon=s.lon,
                           source=synth.SOURCE))
        elif row.lat is None or row.lon is None:
            row.lat, row.lon = s.lat, s.lon
    db.flush()
    rows = 0
    for t in synth.generate_trains():
        tr = TrainRow(id=uuid7(), number=t.number, name=t.name, kind=t.kind, running_days=t.running_days,
                      classes=",".join(t.classes), source=synth.SOURCE, snapshot=run.as_of)
        db.add(tr)
        db.flush()
        for i, st in enumerate(t.stops):
            db.add(TrainStop(id=uuid7(), train_id=tr.id, seq=i, station_code=st.station, arr_min=st.arr,
                             dep_min=st.dep, distance_km=st.distance_km))
            rows += 1
    run.rows, run.status, run.finished_at = rows, "succeeded", utcnow()
    db.commit()
    invalidate()
    return rows


def invalidate() -> None:
    with _lock:
        _cache.clear()
        _cache["key"] = None


def active_import(db: Session) -> TimetableImport | None:
    return db.scalar(select(TimetableImport).where(TimetableImport.status == "active"))


def _active_key(db: Session):
    """The active import's id (a UUID), or "synthetic"."""
    return db.scalar(select(TimetableImport.id).where(TimetableImport.status == "active")) or "synthetic"


def _load(db: Session, key) -> dict:
    q = select(TrainRow.id, TrainRow.number, TrainRow.name, TrainRow.kind, TrainRow.running_days,
               TrainRow.classes, TrainRow.running_days_known, TrainRow.distance_basis)
    q = q.where(TrainRow.source == synth.SOURCE, TrainRow.dataset_id.is_(None)) if key == "synthetic" \
        else q.where(TrainRow.dataset_id == key)
    heads = db.execute(q.order_by(TrainRow.number)).all()
    stops: dict = defaultdict(list)
    ids = [h.id for h in heads]
    for chunk in range(0, len(ids), 2000):
        part = ids[chunk:chunk + 2000]
        for s in db.execute(select(TrainStop.train_id, TrainStop.station_code, TrainStop.arr_min, TrainStop.dep_min,
                                   TrainStop.distance_km).where(TrainStop.train_id.in_(part))
                            .order_by(TrainStop.train_id, TrainStop.seq)):
            stops[s.train_id].append(Stop(s.station_code, s.arr_min, s.dep_min, s.distance_km))
    trains = [Train(h.number, h.name, h.kind, h.running_days, tuple(c for c in h.classes.split(",") if c),
                    stops[h.id], days_known=h.running_days_known, distance_basis=h.distance_basis)
              for h in heads]
    served = {s.station for t in trains for s in t.stops}
    rows = db.execute(select(Station.code, Station.name, Station.state, Station.lat, Station.lon)
                      .where(Station.code.in_(served))).all() if served else []
    stations = {r.code: {"code": r.code, "name": r.name, "state": r.state, "lat": r.lat, "lon": r.lon} for r in rows}
    visits: dict[str, int] = defaultdict(int)
    for t in trains:
        for s in t.stops:
            visits[s.station] += 1
    return {"key": key, "trains": trains, "stations": stations, "names": {c: s["name"] for c, s in stations.items()},
            "visits": dict(visits)}


def _state(db: Session) -> dict:
    key = _active_key(db)
    with _lock:
        if _cache.get("key") == key:
            return dict(_cache)
    state = _load(db, key)
    with _lock:
        _cache.clear()
        _cache.update(state)
    return state


def timetable(db: Session) -> list[Train]:
    return _state(db)["trains"]


def station_names(db: Session) -> dict[str, str]:
    """Names of stations served by the active catalogue."""
    return _state(db)["names"]


def stations(db: Session) -> dict[str, dict]:
    """Stations served by the active catalogue (positions may be None for imported data)."""
    return _state(db)["stations"]


def station_visits(db: Session) -> dict[str, int]:
    return _state(db)["visits"]


def is_large(db: Session) -> bool:
    return len(timetable(db)) > LARGE_TIMETABLE


def provenance(db: Session) -> dict:
    """The `data` block attached to every journey: label plus where the times come from."""
    active = active_import(db)
    if active is None:
        return {"confidence": "simulated", "source": synth.SOURCE, "as_of": synth.SNAPSHOT}
    return {"confidence": "scheduled", "source": active.source_key, "source_name": active.source_name,
            "source_url": active.source_url, "as_of": active.published_on.isoformat(),
            "imported_at": active.activated_at.isoformat() if active.activated_at else None,
            **{k: v for k, v in freshness_label(active.published_on, date.today()).items() if k != "age_days"}}


def freshness(db: Session) -> dict:
    trains = len(timetable(db))
    active = active_import(db)
    if active is not None:
        label = freshness_label(active.published_on, date.today())
        return {
            "status": label["freshness"], "label": "scheduled", "confidence": "scheduled",
            "provider": active.source_key, "dataset": active.source_name, "source_name": active.source_name,
            "source_url": active.source_url, "official": active.official, "licence": active.licence,
            "licence_url": active.licence_url, "as_of": active.published_on.isoformat(),
            "published_on": active.published_on.isoformat(), "published_note": active.published_note,
            "imported_at": active.activated_at.isoformat() if active.activated_at else None,
            "age_days": label["age_days"], "outdated": label["outdated"], "warning": label["warning"],
            "trains": trains, "rows": (active.counts or {}).get("stops"), "running_days_known": False,
            "max_transfers": 1 if trains > LARGE_TIMETABLE else 2,
        }
    run = db.scalar(select(ProviderSyncRun).where(ProviderSyncRun.status == "succeeded")
                    .order_by(ProviderSyncRun.started_at.desc()))
    if run is None or trains == 0:
        return {"status": "empty", "trains": 0, "label": "simulated", "confidence": "simulated", "outdated": False,
                "warning": "No timetable is loaded yet."}
    age = (date.today() - run.as_of).days
    return {"status": "stale" if age > 180 else "ok", "label": "simulated", "confidence": "simulated",
            "provider": run.provider, "dataset": run.dataset, "source_name": "PAYANI synthetic timetable",
            "source_url": None, "official": False, "as_of": run.as_of.isoformat(), "published_on": run.as_of.isoformat(),
            "imported_at": run.finished_at.isoformat() if run.finished_at else None, "age_days": age, "rows": run.rows,
            "trains": trains, "licence": run.licence, "outdated": False, "running_days_known": True,
            "warning": "Simulated timetable: trains and times are invented for this preview and are not real services.",
            "max_transfers": 2}


def count_trains(db: Session) -> int:
    return db.scalar(select(func.count()).select_from(TrainRow)) or 0
